def buscar_por_genero(genero):
    chave = genero.lower().strip()
    return [f for f in FILMES if f["genero"] == chave]


def buscar_por_ator(ator):
    termo = ator.lower().strip()
    return [f for f in FILMES if any(termo in a.lower() for a in f["atores"])]


def buscar_por_diretor(diretor):
    termo = diretor.lower().strip()
    return [f for f in FILMES if termo in f["diretor"].lower()]


def buscar_por_ano(ano):
    try:
        valor = int(ano)
    except ValueError:
        return []
    return [f for f in FILMES if f["ano"] == valor]


def buscar_por_titulo(titulo):
    termo = titulo.lower().strip()
    for f in FILMES:
        if termo in f["titulo"].lower():
            return f
    return None


def formatar_lista(filmes, limite=5):
    if not filmes:
        return "Não encontrei filmes nessa categoria no meu catálogo."
    nomes = [f["titulo"] for f in filmes[:limite]]
    return "Sugestões: " + ", ".join(nomes) + "."


def detalhes_filme(filme):
    atores = ", ".join(filme["atores"])
    return (
        f"**{filme['titulo']}** ({filme['ano']})\n"
        f"Gênero: {filme['genero'].replace('_', ' ').title()}\n"
        f"Diretor: {filme['diretor']}\n"
        f"Elenco: {atores}\n"
        f"Plataforma: {filme['plataforma']}\n"
        f"Classificação: {filme['classificacao']}\n\n"
        f"{filme['sinopse']}"
    )
